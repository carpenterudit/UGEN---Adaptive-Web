    async def _add_button(self, prompt: str, current_spec, project_id: str) -> dict:
        btn_label = "Click Me"
        import re
        m = re.search(r'(?:add|create)\s+(?:a\s+)?(?:"([^"]+)"|\'([^\']+)\'|(\w+(?:\s+\w+){0,3}))\s+button', prompt)
        if m:
            btn_label = (m.group(1) or m.group(2) or m.group(3) or "Click Me").strip().title()
        if current_spec is None:
            base = (await self._login_form(prompt, None, project_id))["ui_spec"]
            current_spec = UISpecification(**base)
        btn_id = f"btn-{_new_id()}"
        if current_spec.pages:
            current_spec.pages[0].components.append(
                ComponentSpec(id=btn_id, type="button", props={"label": btn_label, "variant": "secondary"})
            )
        return {"operation_type": "ADD_COMPONENT", "ui_spec": current_spec.model_dump(), "explanation": f"I've added a '{btn_label}' button."}

