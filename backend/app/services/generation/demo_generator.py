"""
Demo Generator - Deterministic UI generation for demo mode.
Handles common UI patterns without requiring an AI API key.
Clearly labeled as demo mode - not real LLM generation.
"""
from __future__ import annotations
import re
import uuid
import logging
from app.schemas.ui_spec import UISpecification, PageSpec, ComponentSpec, ThemeSpec, NavigationItem, ValidationRule

logger = logging.getLogger(__name__)


def _new_id() -> str:
    return str(uuid.uuid4())[:8]


class DemoGenerator:
    """
    Deterministic demo handler for common UI generation requests.
    Does NOT call any AI API. Responses are rule-based.
    """

    def __init__(self):
        self.patterns = [
            (r"login|sign.?in", self._login_form),
            (r"register|sign.?up|create.?account", self._registration_form),
            (r"contact.?form|contact.?us", self._contact_form),
            (r"student.?dashboard|learner.?dashboard", self._student_dashboard),
            (r"task.?manager|todo|to-do", self._task_manager),
            (r"e.?commerce|shop|product.?list", self._ecommerce),
            (r"dashboard", self._generic_dashboard),
            (r"phone|telephone", self._add_phone_field),
            (r"date.?of.?birth|birthday|dob", self._add_dob_field),
            (r"theme.*(green|blue|red|purple|orange|teal|pink|dark|light)", self._change_theme),
            (r"(green|blue|red|purple|orange|teal|pink|dark|light).*(theme|color|colour)", self._change_theme),
            (r"dark.?mode|night.?mode", self._dark_mode),
            (r"light.?mode", self._light_mode),
            (r"add.*(button|btn)", self._add_button),
            (r"add.*(field|input)", self._add_generic_field),
            (r"two.?col|2.?col|multi.?col", self._two_column_layout),
            (r"responsive|mobile.?friend", self._make_responsive),
            (r"full.?width", self._full_width_button),
            (r"furniture|living.?room|decor|chair|table", self._furniture_store),
            (r"portfolio|3d.?rotating|cinematic|sculpture", self._cinematic_portfolio),
            (r"restaurant|dining|menu|booking|reservation|bistro|cafe", self._restaurant_booking),
            (r"futuristic|product.?landing|quantum|gadget", self._futuristic_landing),
            (r"terms.*(condition|service)|checkbox", self._add_terms_checkbox),
        ]

    async def generate(
        self,
        prompt: str,
        current_spec: UISpecification | None,
        project_id: str,
    ) -> dict:
        """Generate or modify UI spec based on prompt."""
        prompt_lower = prompt.lower().strip()
        logger.info(f"[DEMO MODE] Processing: {prompt_lower[:80]}")

        handler = None
        for pattern, fn in self.patterns:
            if re.search(pattern, prompt_lower):
                handler = fn
                break

        if handler is None:
            handler = self._generic_response

        try:
            result = await handler(prompt_lower, current_spec, project_id)
            result["is_demo"] = True
            result["demo_note"] = "This response is generated by the deterministic demo engine, not a real AI model."
            return result
        except Exception as e:
            logger.error(f"Demo generation error: {e}", exc_info=True)
            return {
                "is_demo": True,
                "operation_type": "ERROR",
                "explanation": f"Demo generation error: {str(e)}",
                "ui_spec": current_spec.model_dump() if current_spec else None,
            }

