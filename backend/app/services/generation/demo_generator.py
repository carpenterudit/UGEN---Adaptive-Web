    async def _add_phone_field(self, prompt: str, current_spec, project_id: str) -> dict:
        if current_spec is None:
            return await self._registration_form("register with phone " + prompt, current_spec, project_id)

        # Add phone field to first form found
        for page in current_spec.pages:
            for comp in page.components:
                if comp.type == "form" and comp.children:
                    # Insert after email field or at position 2
                    insert_at = 2
                    for i, child in enumerate(comp.children):
                        if "email" in child.id:
                            insert_at = i + 1
                    phone_comp = ComponentSpec(
                        id="phone-number",
                        type="text-input",
                        props={"label": "Phone Number", "placeholder": "Enter your phone number", "icon": "phone"},
                        validation=ValidationRule(required=False, pattern=r"^\+?[\d\s\-\(\)]{7,15}$"),
                    )
                    comp.children.insert(insert_at, phone_comp)
                    return {
                        "operation_type": "ADD_COMPONENT",
                        "ui_spec": current_spec.model_dump(),
                        "explanation": "I've added a phone number field to the form.",
                    }

        return {"operation_type": "EXPLAIN_REQUEST", "ui_spec": current_spec.model_dump(), "explanation": "I couldn't find a form to add the phone field to. Please create a form first."}

    async def _add_dob_field(self, prompt: str, current_spec, project_id: str) -> dict:
        if current_spec is None:
            return await self._registration_form("register " + prompt, current_spec, project_id)
        for page in current_spec.pages:
            for comp in page.components:
                if comp.type == "form" and comp.children:
                    dob_comp = ComponentSpec(
                        id="date-of-birth",
                        type="text-input",
                        props={"label": "Date of Birth", "placeholder": "YYYY-MM-DD", "icon": "calendar"},
                    )
                    comp.children.insert(2, dob_comp)
                    return {"operation_type": "ADD_COMPONENT", "ui_spec": current_spec.model_dump(), "explanation": "I've added a date of birth field."}
        return {"operation_type": "EXPLAIN_REQUEST", "ui_spec": current_spec.model_dump(), "explanation": "No form found to add the date of birth field."}

    def _extract_color(self, prompt: str) -> tuple[str, str]:
        """Extract color name and hex from prompt."""
        colors = {
            "green": "#10b981", "blue": "#007BA7", "cerulean": "#007BA7",
            "rose": "#FF2D95", "pink": "#FF2D95", "neon rose": "#FF2D95",
            "red": "#ef4444", "purple": "#8b5cf6", "orange": "#f97316",
            "teal": "#14b8a6", "indigo": "#6366f1", "yellow": "#f59e0b",
        }
        for name, hex_val in colors.items():
            if name in prompt:
                return name, hex_val
        return "neon rose", "#FF2D95"

    async def _change_theme(self, prompt: str, current_spec, project_id: str) -> dict:
        is_dark = "dark" in prompt
        color_name, hex_val = self._extract_color(prompt)
        if current_spec is None:
            base_spec = (await self._login_form(prompt, None, project_id))["ui_spec"]
            current_spec = UISpecification(**base_spec)
        current_spec.theme.primary = hex_val
        if is_dark or "dark" in prompt:
            current_spec.theme.mode = "dark"
        elif "light" in prompt:
            current_spec.theme.mode = "light"
        return {
            "operation_type": "UPDATE_THEME",
            "ui_spec": current_spec.model_dump(),
            "explanation": f"I've updated the theme primary color to {color_name} ({hex_val}).",
        }

